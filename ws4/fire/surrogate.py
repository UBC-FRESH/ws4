"""Deterministic synthetic burn corpus for the P159 fire surrogate.

The corpus is generated by the auditable WS4 FBP growth kernel. It is a training and
evaluation substrate for a surrogate only; it is not observed-fire evidence.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import numpy as np

from .fuel import FireFuelError
from .growth import GROWTH_MODEL_VERSION, GrowthConfig, SiteGrid, grow_fire

CORPUS_SCHEMA_VERSION: Final[str] = "ws4.fire-surrogate-corpus.v1"
SURROGATE_FUEL_ORDER: Final[tuple[str, ...]] = (
    "C1",
    "C2",
    "C3",
    "C4",
    "C5",
    "C6",
    "C7",
    "D1",
    "M1",
    "M2",
    "M3",
    "M4",
    "S1",
    "S2",
    "S3",
    "O1A",
    "O1B",
)


@dataclass(frozen=True)
class SurrogateSample:
    """One synthetic burn case and its kernel target.

    Parameters
    ----------
    sample_id : str
        Stable sample identifier.
    split : str
        ``train`` or ``validation``.
    fuel_index : numpy.ndarray
        Fuel index grid; 0 is non-fuel, otherwise 1-based into the corpus fuel order.
    slope_percent, aspect_deg : numpy.ndarray
        Terrain grids.
    ignition : tuple of int
        Ignition cell as ``(row, col)``.
    wind_kmh, wind_direction_deg, ffmc, bui : float
        Weather inputs.
    duration_min : float
        Simulation duration.
    arrival_time_min : numpy.ndarray
        Kernel arrival time per cell; infinity for unburned cells.
    burned_mask : numpy.ndarray
        Boolean burned mask at ``duration_min``.
    """

    sample_id: str
    split: str
    fuel_index: np.ndarray
    slope_percent: np.ndarray
    aspect_deg: np.ndarray
    ignition: tuple[int, int]
    wind_kmh: float
    wind_direction_deg: float
    ffmc: float
    bui: float
    duration_min: float
    arrival_time_min: np.ndarray
    burned_mask: np.ndarray

    def __post_init__(self) -> None:
        """Validate the sample contract."""
        if not self.sample_id:
            raise FireFuelError("sample_id must be non-empty")
        if self.split not in {"train", "validation"}:
            raise FireFuelError("split must be train or validation")
        shape = self.fuel_index.shape
        if len(shape) != 2 or shape[0] < 2 or shape[1] < 2:
            raise FireFuelError("fuel_index must be a 2-D grid")
        for name, array in (
            ("slope_percent", self.slope_percent),
            ("aspect_deg", self.aspect_deg),
            ("arrival_time_min", self.arrival_time_min),
            ("burned_mask", self.burned_mask),
        ):
            if np.asarray(array).shape != shape:
                raise FireFuelError(f"{name} must match fuel_index shape")
        if self.burnable_count == 0:
            raise FireFuelError("sample must contain at least one burnable cell")

    @property
    def shape(self) -> tuple[int, int]:
        """Return the grid shape.

        Returns
        -------
        tuple of int
            Rows and columns.
        """
        return int(self.fuel_index.shape[0]), int(self.fuel_index.shape[1])

    @property
    def burnable_count(self) -> int:
        """Return the number of burnable cells.

        Returns
        -------
        int
            Count of cells with a non-zero fuel index.
        """
        return int((self.fuel_index > 0).sum())

    @property
    def burned_count(self) -> int:
        """Return the number of burned cells.

        Returns
        -------
        int
            Count of cells in the burned mask.
        """
        return int(np.asarray(self.burned_mask, dtype=bool).sum())

    def to_metadata(self) -> dict[str, object]:
        """Return sample metadata without the arrays.

        Returns
        -------
        dict
            Identity, split, weather, ignition, duration, and cell counts.
        """
        return {
            "sample_id": self.sample_id,
            "split": self.split,
            "shape": list(self.shape),
            "ignition": list(self.ignition),
            "wind_kmh": self.wind_kmh,
            "wind_direction_deg": self.wind_direction_deg,
            "ffmc": self.ffmc,
            "bui": self.bui,
            "duration_min": self.duration_min,
            "burnable_cells": self.burnable_count,
            "burned_cells": self.burned_count,
        }


@dataclass(frozen=True)
class SurrogateCorpus:
    """A generated corpus and its manifest.

    Parameters
    ----------
    seed : int
        Corpus seed.
    rows, cols : int
        Grid dimensions.
    cell_size_m : float
        Cell side length in metres.
    duration_min : float
        Simulation duration.
    samples : tuple of SurrogateSample
        Generated samples.
    """

    seed: int
    rows: int
    cols: int
    cell_size_m: float
    duration_min: float
    samples: tuple[SurrogateSample, ...]

    def __post_init__(self) -> None:
        """Validate corpus shape and split."""
        if self.rows < 2 or self.cols < 2:
            raise FireFuelError("corpus grid must be at least 2 x 2")
        if not self.samples:
            raise FireFuelError("corpus must contain at least one sample")
        for sample in self.samples:
            if sample.shape != (self.rows, self.cols):
                raise FireFuelError("sample shape does not match the corpus grid")
        ids = [sample.sample_id for sample in self.samples]
        if len(ids) != len(set(ids)):
            raise FireFuelError("sample ids must be unique")

    def manifest(self) -> dict[str, object]:
        """Return the full JSON-serializable corpus manifest.

        Returns
        -------
        dict
            Schema, kernel, grid, fuel order, samples, and split counts.
        """
        train = sum(sample.split == "train" for sample in self.samples)
        validation = len(self.samples) - train
        return {
            "schema_version": CORPUS_SCHEMA_VERSION,
            "kernel_version": GROWTH_MODEL_VERSION,
            "seed": self.seed,
            "rows": self.rows,
            "cols": self.cols,
            "cell_size_m": self.cell_size_m,
            "duration_min": self.duration_min,
            "fuel_order": list(SURROGATE_FUEL_ORDER),
            "sample_count": len(self.samples),
            "train_count": train,
            "validation_count": validation,
            "samples": [sample.to_metadata() for sample in self.samples],
        }


def generate_corpus(
    *,
    count: int,
    seed: int,
    rows: int = 32,
    cols: int = 32,
    cell_size_m: float = 100.0,
    duration_min: float = 60.0,
) -> SurrogateCorpus:
    """Generate a deterministic synthetic burn corpus.

    Parameters
    ----------
    count : int
        Number of samples.
    seed : int
        Corpus seed.
    rows, cols : int, optional
        Grid dimensions (default 32 x 32).
    cell_size_m : float, optional
        Cell side length (default 100 m).
    duration_min : float, optional
        Burn duration (default 60 min).

    Returns
    -------
    SurrogateCorpus
        Generated corpus.

    Raises
    ------
    FireFuelError
        If the count or geometry is invalid.
    """
    if count < 2:
        raise FireFuelError("corpus count must be at least 2")
    rng = np.random.default_rng(seed)
    samples: list[SurrogateSample] = []
    for index in range(count):
        split = "validation" if index % 5 == 0 else "train"
        fuel_index = rng.integers(
            1, len(SURROGATE_FUEL_ORDER) + 1, size=(rows, cols), dtype=np.uint8
        )
        nonfuel = rng.random((rows, cols)) < 0.08
        fuel_index[nonfuel] = 0
        burnable = fuel_index > 0
        if not burnable.any():
            burnable[rows // 2, cols // 2] = True
            fuel_index[rows // 2, cols // 2] = 2
        candidates = np.argwhere(burnable)
        ignition_point = candidates[rng.integers(0, len(candidates))]
        ignition = (int(ignition_point[0]), int(ignition_point[1]))
        slope = 0.0 if 6 in fuel_index else float(rng.uniform(0.0, 35.0))
        aspect = float(rng.uniform(0.0, 360.0))
        slope_grid = np.full((rows, cols), slope, dtype=float)
        aspect_grid = np.full((rows, cols), aspect, dtype=float)
        wind = float(rng.uniform(5.0, 35.0))
        direction = float(rng.uniform(0.0, 360.0))
        ffmc = float(rng.uniform(80.0, 98.0))
        bui = float(rng.uniform(20.0, 120.0))
        fuel_grid = np.empty((rows, cols), dtype=object)
        for row in range(rows):
            for col in range(cols):
                value = int(fuel_index[row, col])
                fuel_grid[row, col] = None if value == 0 else SURROGATE_FUEL_ORDER[value - 1]
        grid = SiteGrid(
            fuel_type="C2",
            rows=rows,
            cols=cols,
            cell_size_m=cell_size_m,
            ffmc=ffmc,
            bui=bui,
            wind_kmh=wind,
            wind_direction_deg=direction,
            slope_percent=slope,
            aspect_deg=aspect,
            burnable=burnable,
            fuel_type_grid=fuel_grid,
            slope_percent_grid=slope_grid,
            aspect_deg_grid=aspect_grid,
        )
        growth = grow_fire(
            grid,
            GrowthConfig(
                ignition_cells=(ignition,),
                max_time_min=duration_min,
                snapshot_interval_min=duration_min,
                neighbor_radius=2,
            ),
        )
        samples.append(
            SurrogateSample(
                sample_id=f"sample_{index:04d}",
                split=split,
                fuel_index=fuel_index,
                slope_percent=slope_grid,
                aspect_deg=aspect_grid,
                ignition=ignition,
                wind_kmh=wind,
                wind_direction_deg=direction,
                ffmc=ffmc,
                bui=bui,
                duration_min=duration_min,
                arrival_time_min=growth.ignition_time_min,
                burned_mask=np.isfinite(growth.ignition_time_min),
            )
        )
    return SurrogateCorpus(
        seed=seed,
        rows=rows,
        cols=cols,
        cell_size_m=cell_size_m,
        duration_min=duration_min,
        samples=tuple(samples),
    )


def save_corpus(corpus: SurrogateCorpus, directory: str | Path) -> Path:
    """Write a corpus as a manifest plus compressed arrays.

    Parameters
    ----------
    corpus : SurrogateCorpus
        Corpus to write.
    directory : str or Path
        Destination directory.

    Returns
    -------
    Path
        The manifest path.
    """
    root = Path(directory)
    root.mkdir(parents=True, exist_ok=True)
    arrays: dict[str, np.ndarray] = {}
    for sample in corpus.samples:
        prefix = sample.sample_id
        arrays[f"{prefix}_fuel_index"] = sample.fuel_index
        arrays[f"{prefix}_slope_percent"] = sample.slope_percent
        arrays[f"{prefix}_aspect_deg"] = sample.aspect_deg
        arrays[f"{prefix}_arrival_time_min"] = sample.arrival_time_min
        arrays[f"{prefix}_burned_mask"] = sample.burned_mask
    np.savez_compressed(
        str(root / "samples.npz"),
        **arrays,  # type: ignore[arg-type]  # numpy stubs do not model dynamic savez kwargs
    )
    manifest_path = root / "manifest.json"
    manifest_path.write_text(
        json.dumps(corpus.manifest(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return manifest_path


def load_corpus(directory: str | Path) -> SurrogateCorpus:
    """Load a corpus written by :func:`save_corpus`.

    Parameters
    ----------
    directory : str or Path
        Corpus directory.

    Returns
    -------
    SurrogateCorpus
        Loaded corpus.

    Raises
    ------
    FireFuelError
        If the manifest or arrays are missing or inconsistent.
    """
    root = Path(directory)
    manifest_path = root / "manifest.json"
    if not manifest_path.is_file():
        raise FireFuelError(f"corpus manifest does not exist: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    arrays_path = root / "samples.npz"
    if not arrays_path.is_file():
        raise FireFuelError(f"corpus arrays do not exist: {arrays_path}")
    with np.load(arrays_path, allow_pickle=False) as data:
        samples = []
        for item in manifest["samples"]:
            prefix = str(item["sample_id"])
            ignition = tuple(int(value) for value in item["ignition"])
            samples.append(
                SurrogateSample(
                    sample_id=prefix,
                    split=str(item["split"]),
                    fuel_index=np.asarray(data[f"{prefix}_fuel_index"]),
                    slope_percent=np.asarray(data[f"{prefix}_slope_percent"]),
                    aspect_deg=np.asarray(data[f"{prefix}_aspect_deg"]),
                    ignition=(ignition[0], ignition[1]),
                    wind_kmh=float(item["wind_kmh"]),
                    wind_direction_deg=float(item["wind_direction_deg"]),
                    ffmc=float(item["ffmc"]),
                    bui=float(item["bui"]),
                    duration_min=float(item["duration_min"]),
                    arrival_time_min=np.asarray(data[f"{prefix}_arrival_time_min"]),
                    burned_mask=np.asarray(data[f"{prefix}_burned_mask"], dtype=bool),
                )
            )
    return SurrogateCorpus(
        seed=int(manifest["seed"]),
        rows=int(manifest["rows"]),
        cols=int(manifest["cols"]),
        cell_size_m=float(manifest["cell_size_m"]),
        duration_min=float(manifest["duration_min"]),
        samples=tuple(samples),
    )

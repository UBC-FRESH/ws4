"""Regression tests for the re-implemented stand density equations.

The reference values were generated by running the published ``dmd.volume``
function from the BC Government SDMD app's ``standview.R`` on the same metric
inputs. They are a cross-implementation check, not a claim that the R code is the
definition. The equation sources are cited in ``ws4.sdmd.equations``.
"""

from __future__ import annotations

import math

import pytest
from ws4.sdmd.equations import (
    EQUATIONS,
    SdmdEquationError,
    basal_area_m2_ha,
    biomass_mg_ha,
    crown_cover_pct,
    equation_spec,
    quadratic_mean_diameter_cm,
    relative_density,
    self_thinning_qmd_cm,
    stand_density_index,
    top_height_m,
    trees_per_hectare,
    volume_isoline,
    volume_m3_ha,
)


def test_conversions_round_trip() -> None:
    """Basal area, QMD, and TPH are one consistent geometry."""
    ba = basal_area_m2_ha(1000.0, 25.0)
    assert ba == pytest.approx(math.pi * 0.25 * 25.0 * 1000.0 / 4.0 / 100.0)
    assert quadratic_mean_diameter_cm(ba, 1000.0) == pytest.approx(25.0)
    assert trees_per_hectare(ba, 25.0) == pytest.approx(1000.0)


def test_stand_density_index_uses_the_reference_diameter() -> None:
    """The 25.4 cm reference reproduces the BC app's metric convention."""
    assert stand_density_index(1000.0, 25.4) == pytest.approx(1000.0)
    assert stand_density_index(1000.0, 25.0) == pytest.approx(1000.0 * (25.0 / 25.4) ** 1.605)


def test_relative_density_and_self_thinning_are_consistent() -> None:
    """At the self-thinning diameter, relative density is one."""
    qmd = self_thinning_qmd_cm(1000.0, 988.0)
    assert relative_density(1000.0, qmd, 988.0) == pytest.approx(1.0)


def test_supported_equation_registry() -> None:
    """The registry exposes the five complete equation sets."""
    assert [item.equation_id for item in EQUATIONS] == [2, 3, 6, 7, 9]
    assert equation_spec(3).has_crown_cover
    assert not equation_spec(2).has_top_height
    with pytest.raises(SdmdEquationError, match="unsupported equation"):
        equation_spec(15)


@pytest.mark.parametrize(
    ("equation_id", "tph", "qmd_cm", "volume", "height"),
    [
        (2, 500.0, 15.0, 24.116694, None),
        (2, 500.0, 25.0, 134.629827, None),
        (2, 1000.0, 25.0, 279.895496, None),
        (2, 1500.0, 35.0, 1107.366576, None),
        (3, 500.0, 15.0, 29.039020, 10.063596),
        (3, 1000.0, 25.0, 298.075807, 22.669891),
        (3, 1500.0, 35.0, 1297.273671, 38.626790),
        (6, 500.0, 15.0, 31.513348, 10.104012),
        (6, 1000.0, 35.0, 752.928491, 34.337039),
        (7, 500.0, 15.0, 40.180876, 12.485922),
        (7, 1000.0, 25.0, 492.374524, 26.308369),
        (7, 1500.0, 35.0, 3293.045658, 53.910035),
        (9, 500.0, 15.0, 43.697274, 12.066830),
        (9, 1000.0, 25.0, 403.006242, 20.311742),
        (9, 1500.0, 35.0, 1651.875195, 27.962899),
    ],
)
def test_volume_and_height_match_the_reference_implementation(
    equation_id: int,
    tph: float,
    qmd_cm: float,
    volume: float,
    height: float | None,
) -> None:
    """The Python equations reproduce the BC app's published calculations."""
    assert volume_m3_ha(equation_id, tph, qmd_cm) == pytest.approx(volume, rel=1e-6)
    if height is not None:
        assert top_height_m(equation_id, tph, qmd_cm) == pytest.approx(height, rel=1e-6)


def test_crown_cover_and_biomass_match_the_reference() -> None:
    """Equation 3 also carries crown cover and biomass."""
    assert crown_cover_pct(3, 1000.0, 25.0) == pytest.approx(66.784907, rel=1e-6)
    assert biomass_mg_ha(3, 1000.0, 25.0) == pytest.approx(175.172538, rel=1e-6)
    assert 0.0 <= crown_cover_pct(3, 1500.0, 35.0) <= 100.0


def test_volume_isoline_inverts_the_volume_equation() -> None:
    """The isoline value fed back through the equation returns the target."""
    target = volume_m3_ha(3, 1000.0, 25.0)
    points = volume_isoline(3, target, (500.0, 1000.0, 1500.0))
    assert len(points) == 3
    by_tph = dict(points)
    assert by_tph[1000.0] == pytest.approx(25.0, rel=1e-6)
    assert volume_m3_ha(3, 500.0, by_tph[500.0]) == pytest.approx(target, rel=1e-6)


def test_volume_isoline_omits_unreachable_densities() -> None:
    """A target above the search range is omitted, not clipped."""
    points = volume_isoline(3, 10_000.0, (1000.0,), qmd_bounds=(1.0, 30.0))
    assert points == ()


def test_equation_7_needs_a_maximum_sdi() -> None:
    """The Douglas-fir equation uses maximum SDI for relative density."""
    assert volume_m3_ha(7, 1000.0, 25.0, max_sdi=1482.0) > 0.0
    with pytest.raises(SdmdEquationError, match="max_sdi"):
        volume_m3_ha(7, 1000.0, 25.0, max_sdi=0.0)


def test_equation_6_checks_the_maximum_sdi_range() -> None:
    """The mixed-conifer equation has an accepted maximum-SDI range."""
    with pytest.raises(SdmdEquationError, match="between 1112 and 1482"):
        volume_m3_ha(6, 1000.0, 25.0, max_sdi=2000.0)


def test_equations_without_a_family_are_refused() -> None:
    """A caller cannot ask equation 2 for a top height."""
    with pytest.raises(SdmdEquationError, match="no top-height equation"):
        top_height_m(2, 1000.0, 25.0)
    with pytest.raises(SdmdEquationError, match="no crown-cover equation"):
        crown_cover_pct(6, 1000.0, 25.0)
    with pytest.raises(SdmdEquationError, match="no biomass equation"):
        biomass_mg_ha(9, 1000.0, 25.0)


def test_non_positive_inputs_are_refused() -> None:
    """Zero has no logarithm or geometry."""
    with pytest.raises(SdmdEquationError, match="tph"):
        basal_area_m2_ha(0.0, 20.0)
    with pytest.raises(SdmdEquationError, match="qmd_cm"):
        volume_m3_ha(3, 1000.0, 0.0)
    with pytest.raises(SdmdEquationError, match="ba_m2_ha"):
        quadratic_mean_diameter_cm(0.0, 10.0)
    with pytest.raises(SdmdEquationError, match="tph"):
        quadratic_mean_diameter_cm(10.0, 0.0)
    with pytest.raises(SdmdEquationError, match="max_sdi"):
        relative_density(1000.0, 25.0, 0.0)


def test_equation_6_refuses_a_tiny_qmd() -> None:
    """The mixed-conifer height equation is undefined below 1.2 inches."""
    with pytest.raises(SdmdEquationError, match=r"1\.2-inch"):
        top_height_m(6, 1000.0, 2.0)
